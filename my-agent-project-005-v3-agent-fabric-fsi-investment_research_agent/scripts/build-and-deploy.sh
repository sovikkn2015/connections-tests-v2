#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────────
# V3 Agent Fabric — build and deploy the frontend to S3 + CloudFront.
#
# This script:
#   1. Reads the Flex Gateway ALB URL from agent-fabric/.gateway-url.txt (if
#      present, injected by the GATEWAY subagent) and writes it into
#      frontend/.env.local so the V3 path lights up. Without it, the build
#      falls back to V2 behaviour.
#   2. Reads the registered Anypoint agent network URL from
#      agent-fabric/.registered-agents.json.
#   3. Resolves the S3 bucket + CloudFront distribution from the V3 SAM stack.
#   4. Runs `npm ci && npm run build`, uploads to S3, invalidates CloudFront.
#   5. Writes a build receipt to agent-fabric/.build-receipts/frontend.json.
#
# Usage:
#   ./scripts/build-and-deploy.sh [stack-name]
# Default stack name: ir-research-v3
# ──────────────────────────────────────────────────────────────────────────

set -euo pipefail

STACK_NAME="${1:-ir-research-v3}"
REGION="${AWS_DEFAULT_REGION:-us-east-1}"
ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
FRONTEND_DIR="${ROOT_DIR}/frontend"
FABRIC_DIR="${ROOT_DIR}/agent-fabric"
RECEIPT_DIR="${FABRIC_DIR}/.build-receipts"
RECEIPT_FILE="${RECEIPT_DIR}/frontend.json"

GATEWAY_URL_FILE="${FABRIC_DIR}/.gateway-url.txt"
REGISTERED_FILE="${FABRIC_DIR}/.registered-agents.json"

mkdir -p "${RECEIPT_DIR}"

echo "=== V3 Frontend Build & Deploy ==="
echo "Stack:      ${STACK_NAME}"
echo "Region:     ${REGION}"
echo "Frontend:   ${FRONTEND_DIR}"

# ── Step 1 — read gateway URL and registered agents if present ──

FLEX_GATEWAY_URL=""
if [ -f "${GATEWAY_URL_FILE}" ]; then
  FLEX_GATEWAY_URL="$(tr -d '[:space:]' < "${GATEWAY_URL_FILE}")"
  echo "Flex Gateway URL from .gateway-url.txt: ${FLEX_GATEWAY_URL}"
else
  echo "No .gateway-url.txt found — V3 frontend will fall back to V2 API Gateway path."
fi

ANYPOINT_ORG_ID=""
ANYPOINT_NETWORK_URL=""
if [ -f "${REGISTERED_FILE}" ]; then
  if command -v jq >/dev/null 2>&1; then
    ANYPOINT_ORG_ID="$(jq -r '.organizationId // empty' "${REGISTERED_FILE}")"
    ANYPOINT_NETWORK_URL="$(jq -r '.networkUrl // empty' "${REGISTERED_FILE}")"
  fi
  echo "Anypoint org: ${ANYPOINT_ORG_ID:-<none>}"
fi

# Write a .env.local so Vite picks these up at build time without stomping .env.
ENV_LOCAL="${FRONTEND_DIR}/.env.local"
{
  echo "# Generated by build-and-deploy.sh — do not edit by hand."
  [ -n "${FLEX_GATEWAY_URL}" ] && echo "VITE_FLEX_GATEWAY_URL=${FLEX_GATEWAY_URL}"
  [ -n "${ANYPOINT_ORG_ID}" ] && echo "VITE_ANYPOINT_ORG_ID=${ANYPOINT_ORG_ID}"
  [ -n "${ANYPOINT_NETWORK_URL}" ] && echo "VITE_ANYPOINT_VISUALIZER_URL=${ANYPOINT_NETWORK_URL}"
} > "${ENV_LOCAL}"

# ── Step 2 — resolve S3 bucket + CloudFront distribution from SAM stack ──

echo ""
echo "--- Resolving SAM stack outputs ---"

BUCKET="$(aws cloudformation describe-stacks \
  --stack-name "${STACK_NAME}" \
  --region "${REGION}" \
  --query "Stacks[0].Outputs[?OutputKey=='FrontendBucketName'].OutputValue" \
  --output text 2>/dev/null || true)"

CF_DOMAIN="$(aws cloudformation describe-stacks \
  --stack-name "${STACK_NAME}" \
  --region "${REGION}" \
  --query "Stacks[0].Outputs[?OutputKey=='FrontendUrl'].OutputValue" \
  --output text 2>/dev/null || true)"

if [ -z "${BUCKET}" ] || [ "${BUCKET}" = "None" ]; then
  echo "ERROR: Could not find FrontendBucketName in stack '${STACK_NAME}'."
  echo "Deploy the SAM stack first."
  exit 1
fi

# Prefer an explicit Output; fall back to Comment-based lookup for older stacks.
CF_DIST_ID="$(aws cloudformation describe-stacks \
  --stack-name "${STACK_NAME}" \
  --region "${REGION}" \
  --query "Stacks[0].Outputs[?OutputKey=='FrontendDistributionId'].OutputValue" \
  --output text 2>/dev/null || true)"

if [ -z "${CF_DIST_ID}" ] || [ "${CF_DIST_ID}" = "None" ]; then
  CF_DIST_ID="$(aws cloudfront list-distributions \
    --query "DistributionList.Items[?Comment=='IR Research Workbench V3 - prod' || Comment=='IR Research Workbench V2 - prod'].Id | [0]" \
    --output text 2>/dev/null || true)"
fi

echo "S3 bucket:         ${BUCKET}"
echo "CloudFront URL:    ${CF_DOMAIN}"
echo "CloudFront dist:   ${CF_DIST_ID:-<not found>}"

# ── Step 3 — build frontend ──

echo ""
echo "--- Building frontend ---"

cd "${FRONTEND_DIR}"

BUILD_STATUS="failed"
LINT_STATUS="skipped"
TEST_STATUS="skipped"

if npm ci; then
  if npm run lint; then LINT_STATUS="passed"; else LINT_STATUS="failed"; fi
  if npm test -- --run; then TEST_STATUS="passed"; else TEST_STATUS="failed"; fi
  if npm run build; then BUILD_STATUS="passed"; else BUILD_STATUS="failed"; fi
fi

if [ "${BUILD_STATUS}" != "passed" ]; then
  echo "ERROR: build failed (lint=${LINT_STATUS} test=${TEST_STATUS})."
  cat > "${RECEIPT_FILE}" <<EOF
{
  "status": "failed",
  "stack": "${STACK_NAME}",
  "build": "${BUILD_STATUS}",
  "lint": "${LINT_STATUS}",
  "test": "${TEST_STATUS}",
  "timestamp": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
EOF
  exit 1
fi

# ── Step 4 — upload + invalidate ──

echo ""
echo "--- Uploading to S3 ---"
aws s3 sync dist/ "s3://${BUCKET}/" --delete --region "${REGION}"

INVALIDATION_ID=""
if [ -n "${CF_DIST_ID}" ] && [ "${CF_DIST_ID}" != "None" ]; then
  echo "--- Invalidating CloudFront cache ---"
  INVALIDATION_ID="$(aws cloudfront create-invalidation \
    --distribution-id "${CF_DIST_ID}" \
    --paths '/*' \
    --region "${REGION}" \
    --query 'Invalidation.Id' \
    --output text)"
  echo "Invalidation ID: ${INVALIDATION_ID}"
fi

# ── Step 5 — write build receipt ──

cat > "${RECEIPT_FILE}" <<EOF
{
  "status": "success",
  "stack": "${STACK_NAME}",
  "region": "${REGION}",
  "bucket": "${BUCKET}",
  "cloudFrontUrl": "${CF_DOMAIN}",
  "cloudFrontDistributionId": "${CF_DIST_ID}",
  "invalidationId": "${INVALIDATION_ID}",
  "flexGatewayUrl": "${FLEX_GATEWAY_URL}",
  "anypointOrgId": "${ANYPOINT_ORG_ID}",
  "build": "${BUILD_STATUS}",
  "lint": "${LINT_STATUS}",
  "test": "${TEST_STATUS}",
  "timestamp": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
EOF

echo ""
echo "=== Frontend Deployed ==="
echo "URL: ${CF_DOMAIN}"
echo "Receipt: ${RECEIPT_FILE}"
